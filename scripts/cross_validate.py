#!/usr/bin/env python
"""Cross-validate this implementation against the upstream project.

For every Python version it can find, the suite is executed twice -- once in
full, once restricted to the cross-validation tests -- and a probe records the
carrier statistics side by side with the upstream reference implementation.
The result is written as a Markdown report.

    uv run python scripts/cross_validate.py
    uv run python scripts/cross_validate.py --versions 3.13 --report -

Interpreter selection uses ``uv``: nothing needs to be installed globally.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_VERSIONS = ("3.10", "3.11", "3.12", "3.13", "3.14")
_PASSED = re.compile(r"(\d+) passed")
_FAILED = re.compile(r"(\d+) failed")
_SKIPPED = re.compile(r"(\d+) skipped")


def _run(version: str, module: str, *arguments: str) -> subprocess.CompletedProcess:
    env = {
        "PYTHONPATH": os.pathsep.join([str(ROOT / "src"), str(ROOT / "tests")]),
        "PYTHONIOENCODING": "utf-8",
    }
    return subprocess.run(
        [
            "uv",
            "run",
            "--no-project",
            "--python",
            version,
            "--with",
            "pytest",
            "python",
            module,
            *arguments,
        ],
        cwd=str(ROOT),
        capture_output=True,
        text=True,
        env={**os.environ, **env},
        timeout=900,
    )


def _counts(output: str) -> dict:
    def first(pattern, default=0):
        found = pattern.search(output)
        return int(found.group(1)) if found else default

    return {
        "passed": first(_PASSED),
        "failed": first(_FAILED),
        "skipped": first(_SKIPPED),
    }


def probe(version: str) -> dict:
    completed = _run(version, str(Path("scripts") / "_probe.py"))
    if completed.returncode != 0:
        detail = completed.stderr.strip().splitlines()
        return {"error": detail[-1] if detail else "probe failed"}
    return json.loads(completed.stdout)


def suite(version: str, marker: str | None = None) -> dict:
    arguments = ["-q", "-p", "no:cacheprovider"]
    if marker:
        arguments += ["-m", marker]
    completed = _run(version, "-m", "pytest", *arguments)
    counts = _counts(completed.stdout + completed.stderr)
    counts["ok"] = completed.returncode == 0
    return counts


def render(rows: list[dict], upstream_commit: str) -> str:
    lines = [
        "# Cross-validation report",
        "",
        "Generated by `scripts/cross_validate.py`. Each row runs the full test suite and the",
        "cross-validation suite on one interpreter, then compares carrier statistics with the",
        f"upstream reference implementation (commit `{upstream_commit}`).",
        "",
        "## Test matrix",
        "",
        "| Python | magic | full suite | cross-validation suite | verdict |",
        "| --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        if "error" in row.get("probe", {}):
            lines.append(f"| {row['version']} | - | not run | not run | {row['probe']['error']} |")
            continue
        probe_data = row["probe"]
        full = row["full"]
        interop = row["interop"]
        verdict = "PASS" if full["ok"] and interop["ok"] else "FAIL"
        lines.append(
            f"| {probe_data['python']} | `{probe_data['magic']}` | "
            f"{full['passed']} passed, {full['failed']} failed, {full['skipped']} skipped | "
            f"{interop['passed']} passed, {interop['failed']} failed | {verdict} |"
        )

    lines += [
        "",
        "## Carrier statistics",
        "",
        "Capacity is the number of payload bytes a carrier can hold without changing size.",
        "`blobs` counts `co_code` runs found in the file; when several code objects share",
        "bytecode, `shared` reports how many are references to an earlier run. Upstream counts",
        "such a run once per code object, which inflates the reported capacity and grows the",
        "file when it re-marshals; this implementation counts physical runs.",
        "",
        "| Python | Carrier | code objects | blobs | shared | capacity | upstream "
        "| file size | upstream file size |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        probe_data = row.get("probe", {})
        if "carriers" not in probe_data:
            continue
        for label, entry in probe_data["carriers"].items():
            if "error" in entry:
                lines.append(
                    f"| {probe_data['short']} | {label} | - | - | - | - | - | - "
                    f"| {entry['error']} |"
                )
                continue
            match = "=" if entry.get("upstream_capacity") == entry["capacity"] else "≠"
            lines.append(
                f"| {probe_data['short']} | {label} | {entry['code_objects']} | {entry['blobs']} | "
                f"{entry['shared_blobs']} | {entry['capacity']} | "
                f"{entry.get('upstream_capacity', '-')} ({match}) | {entry['file_size']} | "
                f"{entry.get('upstream_size', '-')} |"
            )
    lines.append("")
    return "\n".join(lines)


def upstream_commit() -> str:
    head = ROOT / "upstream-ref" / ".git"
    if not head.exists():
        return "not checked out"
    completed = subprocess.run(
        ["git", "-C", str(ROOT / "upstream-ref"), "rev-parse", "HEAD"],
        capture_output=True,
        text=True,
    )
    return completed.stdout.strip() or "unknown"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--versions", default=",".join(DEFAULT_VERSIONS))
    parser.add_argument("--report", default="reports/cross-validation.md")
    args = parser.parse_args()

    versions = [version.strip() for version in args.versions.split(",") if version.strip()]
    rows = []
    for version in versions:
        print(f"== Python {version} ==", flush=True)
        probe_data = probe(version)
        if "error" in probe_data:
            print(f"   probe failed: {probe_data['error']}", flush=True)
            rows.append({"version": version, "probe": probe_data})
            continue
        print(f"   {probe_data['python']}: running tests", flush=True)
        full = suite(version)
        interop = suite(version, marker="interop")
        print(f"   full: {full} | interop: {interop}", flush=True)
        rows.append({"version": version, "probe": probe_data, "full": full, "interop": interop})

    report = render(rows, upstream_commit())
    if args.report == "-":
        print(report)
    else:
        target = ROOT / args.report
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(report, encoding="utf-8")
        print(f"\nreport written to {target}")

    failures = [
        row
        for row in rows
        if row.get("full", {}).get("ok") is False or row.get("interop", {}).get("ok") is False
    ]
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
